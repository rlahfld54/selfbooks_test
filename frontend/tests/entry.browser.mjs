  await page.getByLabel('이름', { exact }).fill(account.name)
  await page.getByLabel('이메일', { exact }).fill(account.email)
  await page.getByLabel('비밀번호', { exact }).fill(account.password)
  await page.getByLabel('비밀번호 확인', { exact }).fill(account.password)
