  await page.reload()
  await page.getByLabel('이메일', { exact }).fill(account.email)
  await page.getByLabel('비밀번호', { exact }).fill('Wrong123!')
  await page.getByRole('button', { name: '로그인', exact }).click()
  await page.getByRole('alert').filter({ hasText: '올바르지' }).waitFor()
  await page.getByLabel('비밀번호', { exact }).fill(account.password)
  await page.getByRole('button', { name: '로그인', exact }).click()
  await page.waitForURL('**/dashboard')
  await page.locator('.ob-dialog').waitFor({ state: 'visible' })
  assert.equal(await page.locator('.ob-dialog[open]').count(), 1)
  await page.getByLabel('사무소 이름').fill('신규 회원 사무소')
  await page.locator('.ob-nav button').nth(4).click()
  await page.getByRole('button', { name: '설정 완료', exact }).click()
  await page.reload()
  await page.getByRole('button', { name: '시작 가이드', exact: false }).waitFor()
  assert.equal(await page.locator('.ob-dialog').isVisible(), false)
  const data = await page.evaluate(k => {
    const session = JSON.parse(sessionStorage.getItem('accounting-pro:mock-session:v1'))
    return { original: JSON.parse(localStorage.getItem(k)), own: JSON.parse(localStorage.getItem(k + ':' + session.id)) }
  }, key)
  assert.equal(data.own.office.name, '신규 회원 사무소')
  assert.notEqual(data.original.office.name, data.own.office.name)
  assert.equal(data.original.completed, true)
  await page.getByRole('button', { name: '로그아웃', exact }).click()
  await page.waitForURL('**/login')
  console.log('PASS registration validation, no plaintext storage, reload login, account-scoped onboarding')

