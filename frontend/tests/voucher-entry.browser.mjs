import assert from 'node:assert/strict'
import { chromium } from '@playwright/test'
import { createOnboardingData } from '../app/features/onboarding/mocks.ts'

const browser = await chromium.launch({ headless: true, executablePath: process.env.SELFBOOKS_BROWSER })
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 900 } })
  await context.addInitScript(data => localStorage.setItem('accounting-pro:onboarding-demo:v1', JSON.stringify(data)), { ...createOnboardingData(), completed: true })
  const page = await context.newPage()
  await page.goto('http://127.0.0.1:3000/journal')
  await page.waitForFunction(() => document.querySelector('#__nuxt')?.__vue_app__?.$nuxt?.isHydrating === false)
  await page.getByLabel('조회 시작일', { exact: true }).fill('2026-11-01')
  await page.getByLabel('조회 종료일', { exact: true }).fill('2026-11-30')
  await page.getByRole('button', { name: '+ 행 추가', exact: true }).click()
  const rows = page.locator('.voucher-grid tbody tr')
  const row = rows.last()
  assert.equal(await row.locator('td').nth(1).innerText(), '2026')
  assert.equal(await row.locator('td').nth(2).innerText(), '11')
  await row.getByLabel(/행 일$/, { exact: false }).click()
  await page.getByRole('textbox', { name: '일', exact: true }).fill('31')
  await page.keyboard.press('Enter')
  await page.getByRole('alert').waitFor()
  await page.getByRole('textbox', { name: '일', exact: true }).fill('12')
  await page.keyboard.press('Enter')
  assert.equal(await page.getByRole('combobox', { name: '구분', exact: true }).evaluate(el => el === document.activeElement), true)
  await row.getByLabel(/행 거래처명$/).click()
  await page.getByRole('textbox', { name: '거래처명', exact: true }).fill('한빛')
  await page.keyboard.press('Enter')
  const dialog = page.getByRole('dialog', { name: '거래처 검색' })
  await dialog.getByRole('button', { name: 'C001 · 한빛문구' }).click()
  assert.equal(await row.getByLabel(/행 거래처코드$/).innerText(), 'C001')
  await row.getByLabel(/행 거래처명$/).click()
  await page.getByRole('textbox', { name: '거래처명', exact: true }).fill('없는거래처')
  await page.keyboard.press('Enter')
  await dialog.getByRole('status').waitFor()
  await page.keyboard.press('Escape')
  assert.equal(await row.getByLabel(/행 거래처코드$/).innerText(), 'C001')
  const count = await rows.count()
  await row.getByLabel(/행 자료수집$/).focus()
  await page.keyboard.press('Enter')
  await page.waitForFunction(n => document.querySelectorAll('.voucher-grid tbody tr').length === n + 1, count)
  assert.equal(await rows.last().getByLabel(/행 일$/).evaluate(el => el === document.activeElement), true)
} finally {
  await browser.close()
}
