import assert from 'node:assert/strict'
import { chromium } from '@playwright/test'
const browser = await chromium.launch({ headless: true, executablePath: process.env.SELFBOOKS_BROWSER })
const base = process.env.SELFBOOKS_TEST_URL || 'http://localhost:3101'
const errors = []
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
  page.on('pageerror', error => errors.push(error.message))
  async function visit(path) {
    assert.equal((await page.goto(base + path)).status(), 200)
    await page.waitForFunction(() => document.querySelector('#__nuxt')?.__vue_app__?.$nuxt?.isHydrating === false)
  }
  await visit('/company')
  assert.equal(await page.getByRole('button', { name: '기초정보관리', exact: true }).getAttribute('aria-expanded'), 'false')
  await page.getByLabel('회사명', { exact: true }).fill('레이아웃 테스트')
  await page.getByRole('heading', { name: '대표자정보', exact: true }).waitFor()
  await page.getByLabel('대표자명', { exact: true }).fill('테스트 대표')
  await page.getByRole('checkbox', { name: '기본정보 검토 확인', exact: true }).check()
  await page.getByLabel('회사명', { exact: true }).fill('수정한 회사')
  assert.equal(await page.getByRole('checkbox', { name: '기본정보 검토 확인', exact: true }).isChecked(), false)
  await page.getByText('재검토 필요', { exact: true }).waitFor()
  await page.getByLabel('회사명', { exact: true }).fill('레이아웃 테스트')
  assert.equal(await page.getByLabel('회사명', { exact: true }).inputValue(), '레이아웃 테스트')
  await page.getByRole('button', { name: '환경등록', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: '취소', exact: true }).click()
  assert.equal(new URL(page.url()).pathname, '/company')
  await page.getByRole('button', { name: '환경등록', exact: true }).click()
  await page.getByRole('button', { name: '페이지 이동', exact: true }).click()
  await page.waitForURL('**/settings')
  await page.getByRole('heading', { name: '기본설정', exact: true }).waitFor()
  await page.getByRole('heading', { name: '자동화규칙', exact: true }).waitFor()
  await page.getByLabel('분류 규칙', { exact: true }).fill('검토할 규칙')
  await page.getByRole('checkbox', { name: '자동화규칙 검토 확인', exact: true }).check()
  await page.getByLabel('분류 규칙', { exact: true }).fill('수정한 규칙')
  assert.equal(await page.getByRole('checkbox', { name: '자동화규칙 검토 확인', exact: true }).isChecked(), false)
  await page.locator('#tab-company').click()
  assert.equal(await page.getByLabel('회사명', { exact: true }).inputValue(), '레이아웃 테스트')
  page.on('dialog', dialog => dialog.accept())
  await visit('/accounts')
  await page.getByLabel('계정과목 검색', { exact: true }).fill('존재하지않는코드')
  await page.getByText('검색 결과가 없습니다. 검색어를 변경하세요.').waitFor()
  await page.getByRole('button', { name: '거래적요관리', exact: true }).click()
  await page.getByText('등록된 거래적요가 없습니다', { exact: true }).waitFor()
  await page.getByRole('button', { name: '연결관계', exact: true }).click()
  await page.getByText('설정된 연결관계가 없습니다', { exact: true }).waitFor()
  for (const path of ['/opening-balances', '/collection', '/closing', '/dashboard']) await visit(path)
  await page.setViewportSize({ width: 390, height: 844 })
  await visit('/company')
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
  assert.deepEqual(errors, [])
  console.log('PASS menu defaults, company sections, unsaved cancel/retain, empty account search, direct routes and mobile layout')
} finally { await browser.close() }
