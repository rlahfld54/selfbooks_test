import assert from 'node:assert/strict'
import { chromium } from '@playwright/test'
import { createOnboardingData } from '../app/features/onboarding/mocks.ts'
const browser = await chromium.launch({ headless: true, executablePath: process.env.SELFBOOKS_BROWSER })
const errors = []
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 900 } })
  await context.addInitScript(data => localStorage.setItem('accounting-pro:onboarding-demo:v1', JSON.stringify(data)), { ...createOnboardingData(), completed: true })
  const page = await context.newPage()
  page.on('pageerror', e => errors.push(e.message))
  page.on('console', m => { if (/hydration/i.test(m.text()) && ['warning', 'error'].includes(m.type())) errors.push(m.text()) })
  const visit = async path => { await page.goto('http://127.0.0.1:3000' + path); await page.waitForFunction(() => document.querySelector('#__nuxt')?.__vue_app__?.$nuxt?.isHydrating === false) }
  await visit('/journal')
  const cell = (r, c) => page.locator(`[data-cell="${r}:${c}"]`)
  await cell(0, 7).click()
  await page.getByRole('textbox', { name: '적요', exact: true }).fill('브라우저 검증 적요')
  await page.keyboard.press('Enter')
  assert.equal(await cell(0, 7).innerText(), '브라우저 검증 적요')
  assert.equal(await cell(0, 8).evaluate(el => el === document.activeElement), true)
  await page.keyboard.press('ArrowDown')
  assert.equal(await cell(1, 8).evaluate(el => el === document.activeElement), true)
  await cell(0, 8).click()
  await page.getByRole('textbox', { name: '차변금액', exact: true }).fill('-1')
  await page.keyboard.press('Enter'); await page.getByRole('alert').waitFor()
  await page.keyboard.press('Escape')
  assert.equal(await cell(0, 8).innerText(), '100,000')
  await page.getByRole('tab', { name: '전표 검증', exact: true }).click()
  await page.getByRole('button', { name: /차변·대변 일치/ }).waitFor()
  await page.getByRole('tab', { name: '증빙자료', exact: true }).click()
  await page.getByText('테스트용 증빙 · 법적 효력 없음').waitFor()
  await page.getByRole('tab', { name: '과거 전표', exact: true }).click()
  await page.locator('.voucher-history-row').first().click()
  assert.equal(await cell(0, 7).innerText(), '브라우저 검증 적요')
  await page.getByRole('button', { name: '탭 고정', exact: true }).click()
  await cell(0, 5).focus()
  assert.equal(await page.getByRole('tab', { name: '과거 전표' }).getAttribute('aria-selected'), 'true')
  await page.getByRole('slider').fill('460')
  await page.getByRole('button', { name: '인사이트 닫기', exact: true }).click()
  await page.getByRole('button', { name: '인사이트 열기', exact: true }).click()
  assert.equal(await page.getByRole('slider').inputValue(), '460')
  await page.getByRole('button', { name: '분개 상세 접기' }).click()
  assert.equal(await page.locator('.voucher-detail').count(), 0)
  await page.getByRole('button', { name: '분개 상세 펼치기' }).click()
  await page.getByRole('button', { name: '+ 행 추가', exact: true }).click()
  assert.equal(await page.locator('.voucher-grid-wrap tbody tr').count(), 19)
  await page.locator('.voucher-grid-wrap input[type=checkbox]').last().check()
  await page.getByRole('button', { name: '선택 삭제 (1)' }).click()
  await page.getByRole('button', { name: '삭제 확인', exact: true }).click()
  assert.equal(await page.locator('.voucher-grid-wrap tbody tr').count(), 18)
  await page.getByRole('button', { name: 'Mock 저장', exact: true }).click()
  await page.getByRole('status').filter({ hasText: 'Mock 저장 완료' }).waitFor()
  await page.getByRole('slider').fill('340')
  await cell(0, 0).focus()
  await page.getByRole('tab', { name: '거래처 정보', exact: true }).click()
  await page.locator('.voucher-grid-wrap').evaluate(el => { el.scrollLeft = 0; el.scrollTop = 0 })
  await page.screenshot({ path: 'tests/screenshots/vouchers-general.png', fullPage: true })
  await page.setViewportSize({ width: 1920, height: 1080 })
  await page.screenshot({ path: 'tests/screenshots/vouchers-wide.png', fullPage: true })
  await page.setViewportSize({ width: 1440, height: 900 })
  await visit('/sales')
  await cell(0, 6).click(); await page.getByRole('textbox', { name: '공급가액', exact: true }).fill('200000'); await page.keyboard.press('Tab')
  assert.equal(await cell(0, 8).innerText(), '210,000')
  await page.getByRole('button', { name: 'Mock 저장', exact: true }).click()
  await page.getByRole('tab', { name: '전표 검증', exact: true }).click()
  await page.screenshot({ path: 'tests/screenshots/vouchers-sales.png', fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  await visit('/journal')
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
  await page.getByRole('button', { name: '인사이트 열기', exact: true }).click()
  await page.getByRole('dialog', { name: '전표 인사이트' }).waitFor()
  await page.keyboard.press('Escape')
  assert.deepEqual(errors, [])
  console.log('PASS vouchers: editing, keyboard, invalid amounts, panels, evidence/history, add/delete/save, sales totals, mobile and hydration')
} finally { await browser.close() }

