import assert from 'node:assert/strict'
import { chromium } from 'playwright'
import { mkdir } from 'node:fs/promises'
const browser = await chromium.launch({ executablePath: process.env.SELFBOOKS_BROWSER, headless: true })
const base = process.env.SELFBOOKS_TEST_URL || 'http://localhost:3000'
const errors = []
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
  page.on('pageerror', e => errors.push(e.message))
  page.on('console', m => { if (/hydration/i.test(m.text()) && ['error','warning'].includes(m.type())) errors.push(m.text()) })
  await page.goto(base)
  const wizard = page.locator('.ob-dialog')
  await wizard.waitFor({ state: 'visible' })
  await mkdir('tests/screenshots', { recursive: true })
  await page.screenshot({ path: 'tests/screenshots/onboarding-desktop.png' })
  await page.getByLabel('사무소 이름').fill('')
  await page.getByRole('button', { name: '다음 단계', exact: true }).click()
  await page.getByRole('alert').filter({ hasText: '필수' }).waitFor()
  await page.getByLabel('사무소 이름').fill('테스트 세무사무소')
  await page.getByRole('button', { name: '다음 단계', exact: true }).click()
  await page.getByRole('button', { name: '직원 초대', exact: true }).click()
  await page.getByLabel('직원 이름', { exact: false }).last().fill('최테스트')
  await page.getByRole('button', { name: '초대 추가', exact: true }).click()
  await page.getByLabel('최테스트 권한').selectOption('관리자')
  await page.getByLabel('최테스트 삭제').click()
  await page.getByLabel('이회계 직원 이름').fill('이수정')
  await page.getByRole('button', { name: '다음 단계', exact: true }).click()
  await page.getByLabel('기본 회계연도').fill('2027')
  await page.getByRole('button', { name: '다음 단계', exact: true }).click()
  await page.getByRole('button', { name: '엑셀 가져오기', exact: true }).click()
  await page.getByRole('button', { name: '확인', exact: true }).click()
  await page.getByRole('button', { name: '거래처 추가', exact: true }).click()
  await page.getByLabel('거래처명').fill('신규 거래처')
  await page.getByRole('button', { name: '거래처 저장', exact: true }).click()
  await page.getByLabel('신규 거래처 수정').click()
  await page.getByLabel('거래처명').fill('수정 거래처')
  await page.getByRole('button', { name: '거래처 저장', exact: true }).click()
  await page.getByLabel('수정 거래처 삭제').click()
  await page.getByRole('button', { name: '나중에 등록하기', exact: false }).click()
  assert.match(await wizard.innerText(), /테스트 세무사무소/)
  assert.match(await wizard.innerText(), /이수정/)
  assert.match(await wizard.innerText(), /2027년/)
  await page.getByLabel('사무소 정보 수정').click()
  assert.equal(await page.getByLabel('사무소 이름').inputValue(), '테스트 세무사무소')
  await page.getByRole('button', { name: '임시 저장', exact: true }).click()
  await page.reload(); await wizard.waitFor({ state: 'visible' })
  assert.equal(await page.getByLabel('사무소 이름').inputValue(), '테스트 세무사무소')
  await page.locator('.ob-nav button').nth(4).click()
  await page.getByRole('button', { name: '설정 완료', exact: true }).click()
  await wizard.waitFor({ state: 'hidden' })
  await page.reload(); await page.getByRole('button', { name: '시작 가이드', exact: false }).waitFor()
  assert.equal(await wizard.isVisible(), false)
  await page.getByRole('heading', { name: '홈 대시보드', exact: true }).waitFor()
  await page.getByRole('button', { name: '시작 가이드', exact: false }).click()
  await page.getByRole('button', { name: '다시 시작', exact: true }).click()
  assert.equal(await page.getByLabel('사무소 이름').inputValue(), '테스트 세무사무소')
  await page.getByRole('button', { name: '테스트 데이터 초기화', exact: true }).click()
  await page.getByRole('button', { name: '초기화', exact: true }).click()
  assert.equal(await page.getByLabel('사무소 이름').inputValue(), '샘플 세무회계사무소')
  await page.setViewportSize({ width: 390, height: 844 })
  await page.screenshot({ path: 'tests/screenshots/onboarding-mobile.png' })
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
  const bounds = await wizard.boundingBox(); assert.ok(bounds.width <= 390 && bounds.height <= 844 * .91)
  await page.getByRole('button', { name: '설정 건너뛰기', exact: true }).click()
  await wizard.waitFor({ state: 'hidden' })
  await page.getByRole('button', { name: '시작 가이드', exact: false }).click()
  await page.getByLabel('환경설정 닫기', { exact: true }).click()
  await wizard.waitFor({ state: 'hidden' })
  await page.evaluate(() => localStorage.setItem('accounting-pro:onboarding-demo:v1', '{broken'))
  await page.reload()
  await wizard.waitFor({ state: 'visible' })
  await page.getByText('저장된 테스트 상태를 읽을 수 없어 기본값으로 시작합니다.', { exact: true }).waitFor()
  assert.equal(await page.getByLabel('사무소 이름').inputValue(), '샘플 세무회계사무소')
  await page.keyboard.press('Escape')
  await wizard.waitFor({ state: 'hidden' })
  const blocked = await browser.newPage()
  await blocked.addInitScript(() => {
    Storage.prototype.setItem = () => { throw new DOMException('Blocked', 'SecurityError') }
  })
  await blocked.goto(base)
  await blocked.locator('.ob-dialog').waitFor({ state: 'visible' })
  await blocked.getByRole('button', { name: '임시 저장', exact: true }).click()
  await blocked.getByText('브라우저 저장소를 사용할 수 없어 현재 화면에서만 유지됩니다.', { exact: true }).first().waitFor()
  await blocked.close()
  assert.deepEqual(errors, [])
  console.log('PASS onboarding: validation, all steps, staff/client CRUD, draft/reload, completion/reload, restart/reset, mobile, skip/close, hydration')
} finally { await browser.close() }
